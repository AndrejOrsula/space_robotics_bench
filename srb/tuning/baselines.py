import hashlib
import math
import os
import stat
from dataclasses import asdict, dataclass
from pathlib import Path

import yaml

from srb.core.algorithms import canonical_algorithm_label
from srb.integrations.algorithms import resolve_algorithm_adapter
from srb.tuning import git_short_sha
from srb.tuning.merge import deep_merge
from srb.tuning.metrics import tail_mean_objective
from srb.tuning.spaces import budget_overrides, wandb_off_overrides
from srb.tuning.trial_exec import (
    TrialSpec,
    build_rand_argv,
    build_train_argv,
    run_bounded_rollout,
    run_trial,
)
from srb.utils.agent_config_catalog import resolve_agent_cfg_path
from srb.utils.path import SRB_HYPERPARAMS_DIR, SRB_LOGS_DIR
from srb.utils.process_supervisor import (
    ProcessKind,
    ProcessPlatformError,
    ProcessSpawnError,
    ProcessStatus,
    run_owned,
)
from srb.utils.publication import ArtifactPublication, default_new_file_mode

# Generated by baseline capture; not shipped with the repository.
DEFAULT_BASELINES_PATH = SRB_HYPERPARAMS_DIR / "tune" / "baselines.yaml"
_DEFAULT_TRIAL_NUM_ENVS = 1024


class BaselineError(RuntimeError):
    """A baseline is missing, degenerate (ref==floor), or could not be captured."""


@dataclass(frozen=True)
class BaselineEntry:
    floor: float
    ref: float
    budget: int
    obs: str
    source_config_path: str  # relative to the hyperparams root
    source_config_sha: str  # git blob SHA of that file's content (staleness key)
    date: str
    objective: str = "ep_return_mean"
    num_envs: int | None = None
    seed: int | None = None
    floor_budget: int | None = None
    srb_git: str | None = None  # repo HEAD at capture (informational)


@dataclass
class BaselineConfig:
    tasks: list[str]
    algo: str
    obs: str = "state"
    budget: int = 10_000_000  # reference-run env-steps (== the trial budget)
    floor_budget: int = 200_000  # random-rollout env-steps (cheap + stationary)
    num_envs: int | None = None
    seed_base: int = 42
    gpus: list[str] | None = None
    objective: str = "ep_return_mean"
    timeout_s: float | None = None
    force: bool = False
    dry_run: bool = False
    hyperparams_root: Path = SRB_HYPERPARAMS_DIR
    out_root: Path = SRB_LOGS_DIR / "tune" / "baseline"
    poll_dt: float = 10.0
    grace_s: float = 60.0


# ------------------------------ content hash ---------------------------------


def config_blob_sha(path: str | Path) -> str:
    """Hash file bytes as a Git blob; use Python hashing only when Git hashing is
    unavailable.
    """
    path = Path(path)
    try:
        result = run_owned(
            ["git", "hash-object", os.fspath(path)],
            kind=ProcessKind.FINITE,
            timeout=10.0,
            capture_output=True,
        )
        if (
            result.status is ProcessStatus.EXITED
            and result.returncode == 0
            and result.cleanup_complete
        ):
            sha = (result.stdout or "").strip()
            if sha:
                return sha
    except (ProcessPlatformError, ProcessSpawnError):
        pass
    data = path.read_bytes()
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


# ------------------------------ persistence ----------------------------------


def _baselines_file(root: str | Path) -> Path:
    return Path(root) / "tune" / "baselines.yaml"


def load_baselines(path: str | Path = DEFAULT_BASELINES_PATH) -> dict:
    """Load ``{(task, algo, obs): BaselineEntry}`` from a baselines file."""
    path = Path(path)
    if not path.is_file():
        return {}
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    out: dict = {}
    for task, algos in (data.get("baselines") or {}).items():
        for algo, obss in (algos or {}).items():
            for obs, entry in (obss or {}).items():
                out[(task, algo, obs)] = BaselineEntry(**entry)
    return out


def save_baselines(entries: dict, path: str | Path = DEFAULT_BASELINES_PATH) -> None:
    """Merge entries under lock, preserving existing baselines via atomic write."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    # The publication stage is created 0o600 (owner-only). An existing
    # baselines file's mode survives the promotion's atomic replace; a
    # brand-new one must have the stage's tightened mode explicitly relaxed
    # to the ordinary umask-respecting default before publish, or it would
    # otherwise land 0o600 instead of the usual `0o666 & ~umask`.
    target_mode = (
        stat.S_IMODE(path.stat().st_mode) if path.exists() else default_new_file_mode()
    )
    with ArtifactPublication.file(path).stage() as stage:
        merged = load_baselines(path)
        merged.update(entries)
        nested: dict = {}
        for (task, algo, obs), e in merged.items():
            nested.setdefault(task, {}).setdefault(algo, {})[obs] = asdict(e)
        stage.path.write_text(
            "# Cross-task normalization baselines for `srb agent tune`.\n"
            "# Generated by `srb agent tune baseline` — do not hand-edit.\n"
            "# floor = random-policy mean return; ref = reference-run tail-mean.\n"
            + yaml.safe_dump({"version": 1, "baselines": nested}, sort_keys=True),
            encoding="utf-8",
        )
        os.chmod(stage.path, target_mode)
        stage.publish()


def load_baseline(
    task: str, algo: str, obs: str, *, root: str | Path = SRB_HYPERPARAMS_DIR
) -> BaselineEntry:
    """Look up a baseline or raise :class:`BaselineError` if missing or degenerate."""
    algo = canonical_algorithm_label(algo)
    path = _baselines_file(root)
    entries = load_baselines(path)
    try:
        entry = entries[(task, algo, obs)]
    except KeyError:
        raise BaselineError(
            f"no baseline for (task={task!r}, algo={algo!r}, obs={obs!r}) in {path}. "
            f"Run `srb agent tune baseline --tasks {task} --algo {algo}` first."
        ) from None
    if entry.ref <= entry.floor:
        raise BaselineError(
            f"degenerate baseline for {task!r}: ref ({entry.ref!r}) <= floor "
            f"({entry.floor!r}); the reference must beat the random-policy floor "
            "(a zero/negative span has no dynamic range or inverts the objective) "
            "— re-capture it."
        )
    return entry


# ------------------------------ staleness ------------------------------------


def baseline_staleness(
    entry: BaselineEntry, *, hyperparams_root: str | Path = SRB_HYPERPARAMS_DIR
) -> str | None:
    """Return a warning if the source config drifted since capture, else ``None``."""
    cfg = Path(hyperparams_root) / entry.source_config_path
    if not cfg.is_file():
        return f"baseline source config {entry.source_config_path} is missing"
    if config_blob_sha(cfg) != entry.source_config_sha:
        return (
            f"baseline source config {entry.source_config_path} changed since "
            "capture — re-run `srb agent tune baseline`"
        )
    return None


def check_baselines_staleness(
    tasks, algo: str, obs: str, *, root: str | Path = SRB_HYPERPARAMS_DIR
) -> list[str]:
    """Collect staleness warnings across a task set (used at ``tune run`` startup)."""
    algo = canonical_algorithm_label(algo)
    entries = load_baselines(_baselines_file(root))
    warnings: list[str] = []
    for t in tasks:
        entry = entries.get((t, algo, obs))
        if entry is not None:
            msg = baseline_staleness(entry, hyperparams_root=root)
            if msg:
                warnings.append(f"[{t}] {msg}")
    return warnings


# ------------------------------ capture --------------------------------------


def measure_floor(
    task: str,
    *,
    budget: int,
    num_envs: int,
    seed: int,
    objective: str,
    out_dir: Path,
    gpu: str | None,
    timeout_s: float | None,
    poll_dt: float,
    grace_s: float,
    rand_command_builder=None,
) -> float:
    """Floor = mean return of a random policy over *budget* env-steps."""
    out_dir = Path(out_dir)
    argv = (
        rand_command_builder(task)
        if rand_command_builder is not None
        else build_rand_argv(
            task, logdir=out_dir / "rand_logs", num_envs=num_envs, seed=seed
        )
    )
    records = run_bounded_rollout(
        argv,
        metrics_path=out_dir / "floor_metrics.jsonl",
        budget_env_steps=budget,
        num_envs=num_envs,
        gpu=gpu,
        poll_dt=poll_dt,
        grace_s=grace_s,
        timeout_s=timeout_s,
    )
    if not records:
        raise BaselineError(f"random rollout for {task!r} produced no metrics")
    # tail=0.0 → mean over all records (a random policy is stationary).
    floor = tail_mean_objective(records, budget, tail=0.0, field=objective)
    if not math.isfinite(floor):
        raise BaselineError(f"random rollout for {task!r} has no finite {objective}")
    return float(floor)


def measure_ref(
    task: str,
    *,
    algo: str,
    obs: str,
    base_agent_cfg: dict,
    framework: str,
    budget: int,
    num_envs: int,
    seed: int,
    out_dir: Path,
    objective: str,
    gpu: str | None,
    timeout_s: float | None,
    poll_dt: float,
    grace_s: float,
    train_command_builder=None,
) -> float:
    """Measure the base-config tail mean via ``run_trial``.

    No Optuna reporting or pruning.
    """
    algo = canonical_algorithm_label(algo)
    out_dir = Path(out_dir)
    merged = deep_merge(
        base_agent_cfg,
        budget_overrides(
            framework,
            trial_env_steps=budget,
            num_envs=num_envs,
            agent_cfg=base_agent_cfg,
        ),
    )
    merged = deep_merge(merged, wandb_off_overrides(framework))
    spec = TrialSpec(
        task=task,
        algo=algo,
        obs=obs,
        agent_section={"agent": merged},
        env_section={"seed": seed, "num_envs": num_envs},
        trial_env_steps=budget,
        num_envs=num_envs,
        metrics_path=out_dir / "ref_metrics.jsonl",
        trial_dir=out_dir,
        logdir=out_dir / "logs",
        gpu=gpu,
        timeout_s=timeout_s,
    )
    outcome = run_trial(
        spec,
        report_cb=lambda rung, val: None,
        should_prune_cb=lambda: False,
        poll_dt=poll_dt,
        objective_field=objective,
        command_builder=(train_command_builder or build_train_argv),
        grace_s=grace_s,
    )
    if outcome.state != "COMPLETE" or outcome.value is None:
        raise BaselineError(
            f"reference run for {task!r} did not complete "
            f"({outcome.state}, {outcome.user_attrs})"
        )
    return float(outcome.value)


def compute_baseline(
    *,
    task: str,
    algo: str,
    obs: str,
    budget: int,
    floor_budget: int,
    num_envs: int,
    seed: int,
    objective: str,
    gpu: str | None,
    out_dir: Path,
    hyperparams_root: str | Path,
    poll_dt: float,
    grace_s: float,
    timeout_s: float | None,
    train_command_builder=None,
    rand_command_builder=None,
) -> BaselineEntry:
    """Capture a full baseline entry: resolve base → floor → ref → validate."""
    if floor_budget <= 0:
        raise ValueError("floor_budget must be a positive integer")
    algo = canonical_algorithm_label(algo)
    hyperparams_root = Path(hyperparams_root)
    framework = resolve_algorithm_adapter(algo).framework
    base_path = resolve_agent_cfg_path(algo, obs=obs, task=task, root=hyperparams_root)
    base_cfg = yaml.safe_load(base_path.read_text(encoding="utf-8")) or {}
    out_dir = Path(out_dir)

    floor = measure_floor(
        task,
        budget=floor_budget,
        num_envs=num_envs,
        seed=seed,
        objective=objective,
        out_dir=out_dir / "floor",
        gpu=gpu,
        timeout_s=timeout_s,
        poll_dt=poll_dt,
        grace_s=grace_s,
        rand_command_builder=rand_command_builder,
    )
    ref = measure_ref(
        task,
        algo=algo,
        obs=obs,
        base_agent_cfg=base_cfg,
        framework=framework,
        budget=budget,
        num_envs=num_envs,
        seed=seed,
        out_dir=out_dir / "ref",
        objective=objective,
        gpu=gpu,
        timeout_s=timeout_s,
        poll_dt=poll_dt,
        grace_s=grace_s,
        train_command_builder=train_command_builder,
    )
    if ref <= floor:
        raise BaselineError(
            f"degenerate baseline for {task!r}: ref ({ref!r}) <= floor ({floor!r}); "
            "the reference run must beat the random-policy floor"
        )
    try:
        rel = base_path.relative_to(hyperparams_root).as_posix()
    except ValueError:
        rel = base_path.as_posix()
    return BaselineEntry(
        floor=floor,
        ref=ref,
        budget=int(budget),
        obs=obs,
        source_config_path=rel,
        source_config_sha=config_blob_sha(base_path),
        date=datetime.datetime.now(tz=datetime.timezone.utc).date().isoformat(),
        objective=objective,
        num_envs=int(num_envs),
        seed=int(seed),
        floor_budget=int(floor_budget),
        srb_git=git_short_sha(),
    )


def run_baseline(cfg: BaselineConfig) -> dict:
    """Capture baselines for every task in *cfg* and persist them (unless dry-run)."""
    if cfg.floor_budget <= 0:
        raise ValueError("floor_budget must be a positive integer")
    algo = canonical_algorithm_label(cfg.algo)
    num_envs = cfg.num_envs or _DEFAULT_TRIAL_NUM_ENVS
    path = _baselines_file(cfg.hyperparams_root)
    # Capture outputs live under <out_root>/<task>; a repeated task would
    # overwrite an earlier capture.
    duplicates = sorted({task for task in cfg.tasks if cfg.tasks.count(task) > 1})
    if duplicates:
        raise BaselineError(f"duplicate baseline task(s): {', '.join(duplicates)}")
    existing = load_baselines(path)
    captured: dict = {}
    for i, task in enumerate(cfg.tasks):
        key = (task, algo, cfg.obs)
        if key in existing and not cfg.force and not cfg.dry_run:
            raise BaselineError(
                f"baseline for {key} already exists — pass --force to re-capture"
            )
        gpu = cfg.gpus[i % len(cfg.gpus)] if cfg.gpus else None
        entry = compute_baseline(
            task=task,
            algo=algo,
            obs=cfg.obs,
            budget=cfg.budget,
            floor_budget=cfg.floor_budget,
            num_envs=num_envs,
            seed=cfg.seed_base + i,
            objective=cfg.objective,
            gpu=gpu,
            out_dir=Path(cfg.out_root) / task,
            hyperparams_root=cfg.hyperparams_root,
            poll_dt=cfg.poll_dt,
            grace_s=cfg.grace_s,
            timeout_s=cfg.timeout_s,
        )
        captured[key] = entry
        # Persist after EACH task (save_baselines merges): a later task's
        # failure must not discard the GPU-hours already spent on earlier ones.
        if not cfg.dry_run:
            save_baselines({key: entry}, path)
    return captured


